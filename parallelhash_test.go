func TestSumParallelHash128(t *testing.T) {
	// NIST test vectors: https://csrc.nist.gov/CSRC/media/Projects/Cryptographic-Standards-and-Guidelines/documents/examples/ParallelHash_samples.pdf
	tests := []struct {
		name      string
		data      []byte
		blockSize int
		length    int
		S         []byte
		want      []byte
	}{
		{
			name: "NIST Sample #1",
			data: []byte{
				0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
				0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
				0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27,
			},
			blockSize: 8,
			length:    32,
			want: []byte{
				0xba, 0x8d, 0xc1, 0xd1, 0xd9, 0x79, 0x33, 0x1d,
				0x3f, 0x81, 0x36, 0x03, 0xc6, 0x7f, 0x72, 0x60,
				0x9a, 0xb5, 0xe4, 0x4b, 0x94, 0xa0, 0xb8, 0xf9,
				0xaf, 0x46, 0x51, 0x44, 0x54, 0xa2, 0xb4, 0xf5,
			},
		},
		{
			name: "NIST Sample #2",
			data: []byte{
				0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
				0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
				0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27,
			},
			blockSize: 8,
			length:    32,
			S:         []byte("Parallel Data"),
			want: []byte{
				0xfc, 0x48, 0x4d, 0xcb, 0x3f, 0x84, 0xdc, 0xee,
				0xdc, 0x35, 0x34, 0x38, 0x15, 0x1b, 0xee, 0x58,
				0x15, 0x7d, 0x6e, 0xfe, 0xd0, 0x44, 0x5a, 0x81,
				0xf1, 0x65, 0xe4, 0x95, 0x79, 0x5b, 0x72, 0x06,
			},
		},
		{
			name: "NIST Sample #3",
			data: []byte{
				0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
				0x08, 0x09, 0x0a, 0x0b, 0x10, 0x11, 0x12, 0x13,
				0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b,
				0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27,
				0x28, 0x29, 0x2a, 0x2b, 0x30, 0x31, 0x32, 0x33,
				0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x3a, 0x3b,
				0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47,
				0x48, 0x49, 0x4a, 0x4b, 0x50, 0x51, 0x52, 0x53,
				0x54, 0x55, 0x56, 0x57, 0x58, 0x59, 0x5a, 0x5b,
			},
			blockSize: 12,
			length:    32,
			S:         []byte("Parallel Data"),
			want: []byte{
				0xf7, 0xfd, 0x53, 0x12, 0x89, 0x6c, 0x66, 0x85,
				0xc8, 0x28, 0xaf, 0x7e, 0x2a, 0xdb, 0x97, 0xe3,
				0x93, 0xe7, 0xf8, 0xd5, 0x4e, 0x3c, 0x2e, 0xa4,
				0xb9, 0x5e, 0x5a, 0xca, 0x37, 0x96, 0xe8, 0xfc,
			},
		},
		{
			name:      "empty string",
			data:      nil,
			blockSize: 8192,
			length:    32,
			want: []byte{
				0xc7, 0xb3, 0x2e, 0x3b, 0x07, 0x1f, 0x7f, 0xb9,
				0xc5, 0x80, 0x54, 0xc9, 0x3c, 0x2f, 0x35, 0xe0,
				0xd8, 0x05, 0x1a, 0x27, 0x0d, 0x6c, 0x01, 0x36,
				0xef, 0x84, 0x92, 0x32, 0xc9, 0x6c, 0xd1, 0xc5,
			},
		},
		{
			name:      "hello world",
			data:      []byte("hello world"),
			blockSize: 8192,
			length:    32,
			want: []byte{
				0xff, 0x4c, 0xd2, 0xea, 0xbf, 0xbe, 0x68, 0xba,
				0x76, 0x09, 0x2b, 0xf0, 0x66, 0x84, 0xb9, 0x02,
				0x0f, 0xba, 0x6f, 0xbc, 0x41, 0xfd, 0x7a, 0x23,
				0x9e, 0x54, 0xae, 0x5b, 0xcb, 0x56, 0xc9, 0xba,
			},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := SumParallelHash128(tt.data, tt.blockSize, tt.length, tt.S); !reflect.DeepEqual(got, tt.want) {
				t.Errorf("SumParallelHash128() = %v, want %v", got, tt.want)
			}
		})
	}
}

